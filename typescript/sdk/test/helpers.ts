import { createServer, type IncomingMessage, type ServerResponse } from "node:http";
import type { AddressInfo } from "node:net";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export interface RecordedRequest {
  method: string;
  url: string;
  headers: IncomingMessage["headers"];
  body: string;
  json: unknown;
}

export type Route = (req: RecordedRequest, res: ServerResponse) => void | Promise<void>;

/** Fake notific.me API: records requests and answers with `route`. */
export async function fakeServer(route: Route) {
  const requests: RecordedRequest[] = [];
  const server = createServer(async (req, res) => {
    const chunks: Buffer[] = [];
    for await (const c of req) chunks.push(c as Buffer);
    const body = Buffer.concat(chunks).toString("utf8");
    let json: unknown;
    try {
      json = body ? JSON.parse(body) : undefined;
    } catch {
      json = undefined;
    }
    const rec: RecordedRequest = { method: req.method ?? "", url: req.url ?? "", headers: req.headers, body, json };
    requests.push(rec);
    try {
      await route(rec, res);
    } catch (err) {
      res.statusCode = 500;
      res.end(String(err));
    }
  });
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const { port } = server.address() as AddressInfo;
  return {
    url: `http://127.0.0.1:${port}`,
    requests,
    close: () =>
      new Promise<void>((resolve) => {
        server.closeAllConnections?.();
        server.close(() => resolve());
      }),
  };
}

export function sendJson(res: ServerResponse, status: number, body: unknown, headers: Record<string, string> = {}) {
  res.writeHead(status, { "Content-Type": "application/json", ...headers });
  res.end(JSON.stringify(body));
}

export interface SignatureVector {
  seed: string;
  key_id: string;
  public_key: string;
  jwks: { keys: { kty: "OKP"; crv: "Ed25519"; x: string; kid: string }[] };
  timestamp: number;
  body: string;
  header: string;
}

/** Vector generated by the Go signer (server/internal/signer/sdk_vector_test.go). */
export const vector: SignatureVector = JSON.parse(
  readFileSync(fileURLToPath(new URL("../../../protocol/test-vectors/webhook-signature.json", import.meta.url)), "utf8"),
);

export const vectorNow = new Date(vector.timestamp * 1000);

/** Headers of a webhook signed with the Go vector. */
export function vectorHeaders(overrides: Record<string, string> = {}): Record<string, string> {
  return {
    "content-type": "application/json",
    "notificme-signature": vector.header,
    "notificme-webhook-id": "019a2b3c-aaaa-7000-8000-000000000001",
    "notificme-topic": "reply",
    "notificme-attempt": "1",
    ...overrides,
  };
}
