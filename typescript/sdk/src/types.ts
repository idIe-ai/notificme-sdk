/**
 * Public, camelCase types of the SDK. The SDK converts them to the
 * snake_case wire format of the notific.me protocol (protocol/schemas).
 */

import type { UntrustedText } from "./untrusted";

/** JSON value. */
export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

export type Severity = "info" | "low" | "medium" | "high" | "critical";
export type Retention = "ephemeral" | "standard" | "regulated";
/** Decision level: 0 = tap, 1 = unlock, 2+ = device signature. */
export type Level = 0 | 1 | 2 | 3 | 4;
/** Duration such as `"30s"`, `"30m"`, `"2h"`, `"3d"`; a number means seconds. */
export type Duration = `${number}${"s" | "m" | "h" | "d"}` | number;

// ---------------------------------------------------------------------------
// Card
// ---------------------------------------------------------------------------

export interface TextBlock {
  type: "text";
  /** Markdown-lite text. */
  text: string;
}
export interface MetricBlock {
  type: "metric";
  label: string;
  value: number | string;
  unit?: string;
  /** e.g. `"+18%"` */
  delta?: string;
}
export interface ChartBlock {
  type: "chart";
  kind: "line" | "bar";
  x?: string[];
  series: { name: string; values: number[] }[];
}
export interface TableBlock {
  type: "table";
  columns: string[];
  rows: (string | number | null)[][];
}
export interface ListBlock {
  type: "list";
  items: { text: string; icon?: string }[];
}
export interface ImageBlock {
  type: "image";
  src: string;
  alt?: string;
}
export interface ProgressBlock {
  type: "progress";
  /** 0..1 */
  value?: number;
  steps?: string[];
  current?: number;
}
export interface ButtonsBlock {
  type: "buttons";
  buttons: { label: string; url?: string; action?: string }[];
}
/** Renders a question of the question set (yesno, single or multi). */
export interface OptionsBlock {
  type: "options";
  questionId: string;
}
/** Renders a question of the question set (text, voice, number or date). */
export interface InputBlock {
  type: "input";
  questionId: string;
}
export type CardBlock =
  | TextBlock
  | MetricBlock
  | ChartBlock
  | TableBlock
  | ListBlock
  | ImageBlock
  | ProgressBlock
  | ButtonsBlock
  | OptionsBlock
  | InputBlock;

export interface Card {
  title?: string;
  theme?: { accent?: string; icon?: string };
  /** 1 to 40 blocks. */
  blocks: CardBlock[];
}

// ---------------------------------------------------------------------------
// Events
// ---------------------------------------------------------------------------

export interface EventContent {
  /** Short text for push, watch and simple channels (max 240 characters). */
  summary: string;
  card?: Card;
  rich?: { htmlRef: string; height?: number };
}

/** Event for `notific.send()`. */
export interface EventInput {
  /**
   * Your own id for the event, used for idempotency. When omitted the SDK
   * generates one, so automatic retries never create duplicates.
   */
  id?: string;
  /** Sender name. Defaults to the client's `source` option. */
  source?: string;
  /** Dotted lowercase type, e.g. `"container.die"`. */
  type: string;
  /** Defaults to `"info"`. */
  severity?: Severity;
  /** Defaults to now. */
  occurredAt?: Date | string;
  /** Recipients (handle, member or group). When omitted, subscriptions decide. */
  to?: string | string[];
  /** Free-form data; sent as is (keys are not converted). */
  payload?: Record<string, unknown>;
  /** Events with the same key within the dedup window are merged. */
  dedupKey?: string;
  /** How long the notification stays relevant, e.g. `"30m"`. */
  ttl?: Duration;
  /** Event type that closes this notification, e.g. `"container.healthy"`. */
  expiresWhen?: string;
  /** Live card id: events with the same `cardId` update the same card. */
  cardId?: string;
  /** When `true` and `cardId` is omitted, the SDK generates a `cardId` (returned in the result). */
  live?: boolean;
  retention?: Retention;
  /** Shortcut for `content.summary`. */
  summary?: string;
  /** Shortcut for `content.card`. */
  card?: Card;
  content?: EventContent;
}

/** Result of `send()` / `update()` (`202 Accepted`). */
export interface SendResult {
  /** Server-side event id. */
  id: string;
  /** `duplicate` when merged by `dedupKey`. */
  status: "queued" | "duplicate";
  duplicateOf?: string;
  /** The event `id` you sent (or the one generated by the SDK). */
  senderId?: string;
  receivedAt: string;
  /** Live card id, when the event has one. Pass it to `update()`. */
  cardId?: string;
  /** `true` when the server returned a stored response for a repeated id. */
  replayed: boolean;
}

// ---------------------------------------------------------------------------
// Questions
// ---------------------------------------------------------------------------

interface QuestionBase<Id extends string> {
  /** Unique id inside the question set; answers are keyed by it. */
  id: Id;
  /** The question shown to the human. */
  text: string;
  /** When `true` the human may skip it (the answer may be `undefined`). */
  optional?: boolean;
  /** Minimum decision level for this question. */
  level?: Level;
}

export interface YesNoQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "yesno";
}
export interface SingleQuestion<Id extends string = string, O extends string = string> extends QuestionBase<Id> {
  type: "single";
  options: readonly O[];
  /** Lets the human type another answer (returned as `UntrustedText`). */
  allowOther?: boolean;
}
export interface MultiQuestion<Id extends string = string, O extends string = string> extends QuestionBase<Id> {
  type: "multi";
  options: readonly O[];
  /** Lets the human add free text (see `details[id].freeText`). */
  allowOther?: boolean;
}
export interface TextQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "text";
}
export interface VoiceQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "voice";
}
export interface NumberQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "number";
}
export interface DateQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "date";
}

export type Question =
  | YesNoQuestion
  | SingleQuestion
  | MultiQuestion
  | TextQuestion
  | VoiceQuestion
  | NumberQuestion
  | DateQuestion;

export type QuestionType = Question["type"];

/** Answer of a `voice` question. */
export interface VoiceAnswer {
  /** Transcription (untrusted). */
  text?: UntrustedText;
  /** Reference of the recorded audio. */
  audioRef?: string;
}

/** Answer value type of a question. */
export type AnswerValue<Q> = Q extends { type: "yesno" }
  ? boolean
  : Q extends { type: "single"; options: readonly (infer O)[] }
    ? Q extends { allowOther: true }
      ? O | UntrustedText
      : O
    : Q extends { type: "multi"; options: readonly (infer O)[] }
      ? O[]
      : Q extends { type: "text" }
        ? UntrustedText
        : Q extends { type: "voice" }
          ? VoiceAnswer
          : Q extends { type: "number" }
            ? number
            : Q extends { type: "date" }
              ? string
              : unknown;

type IsOptional<Q> = Q extends { optional: true } ? true : false;

/** Answers keyed by question id (all present when `status` is `answered`, except optional ones). */
export type Answers<Qs extends readonly Question[]> = {
  [Q in Qs[number] as Q["id"]]: IsOptional<Q> extends true ? AnswerValue<Q> | undefined : AnswerValue<Q>;
};

/** Answers when the question set timed out or was rejected: any of them may be missing. */
export type PartialAnswers<Qs extends readonly Question[]> = {
  [Q in Qs[number] as Q["id"]]: AnswerValue<Q> | undefined;
};

/** Everything the server returned for one answer. */
export interface AnswerDetail {
  questionId: string;
  questionText: string;
  /** Raw value (`true`, `"Approve"`, `["a","b"]`, `42`, `"2026-11-04"`…). */
  value?: JsonValue;
  /** Free text typed by the human. Untrusted. */
  freeText?: UntrustedText;
  audioRef?: string;
}

/**
 * How the person confirmed the answer. `delegated`: inside your own app with a
 * person token (`notific.members.issueToken()`), levels 0 and 1 only.
 */
export type AuthMethod = "tap" | "unlock" | "biometric" | "device_pin" | "app_password" | "totp" | "delegated";

export interface AnsweredBy {
  /** E-mail or handle of who answered. */
  identity: string;
  deviceId: string;
  levelUsed: Level;
  authMethod?: AuthMethod;
}

export interface ReplySignature {
  alg: "ES256" | "Ed25519";
  keyId?: string;
  value: string;
}

interface AskResultBase {
  /** Question set id. */
  id: string;
  version: number;
  /**
   * Natural-language summary of the decision, ready for an AI agent. Free
   * text inside it is quoted and labelled as untrusted by the server.
   */
  asText: string;
  answeredBy?: AnsweredBy;
  answeredAt?: string;
  contentHash?: string;
  signature?: ReplySignature;
  /** Every answer with its question text, raw value and free text. */
  details: Record<string, AnswerDetail>;
  /** The reply exactly as received (snake_case wire format). */
  raw: Record<string, unknown>;
}

export interface AnsweredAskResult<Qs extends readonly Question[]> extends AskResultBase {
  status: "answered";
  timedOut: false;
  answers: Answers<Qs>;
}

export interface UnansweredAskResult<Qs extends readonly Question[]> extends AskResultBase {
  /** `timeout`: nobody answered in time (`onTimeout` values are applied). `rejected`: the human declined. */
  status: "timeout" | "rejected";
  timedOut: boolean;
  answers: PartialAnswers<Qs>;
}

/** Final result of `ask()`. Narrow on `status` to get required answers. */
export type AskResult<Qs extends readonly Question[] = readonly Question[]> =
  | AnsweredAskResult<Qs>
  | UnansweredAskResult<Qs>;

/** Question set for `ask()` / `createAsk()`. */
export interface AskInput<Qs extends readonly Question[] = readonly Question[]> {
  /** Recipients (handle, member or group). When omitted, subscriptions decide. */
  to?: string | string[];
  /** Up to 160 characters. */
  title: string;
  /** Why you are asking (up to 4000 characters). */
  context?: string;
  /** 1 to 20 questions. */
  questions: Qs;
  /** Minimum decision level (default 1). The workspace may require more. */
  level?: Level;
  /** Number of people that must answer (2 or more). */
  quorum?: number;
  /** Whether the app may answer while offline. */
  offline?: "allowed" | "denied";
  /** How long the humans have, e.g. `"30m"`. */
  timeout?: Duration;
  /** Answers applied when nobody answers in time, by question id. */
  onTimeout?: { [K in Qs[number]["id"]]?: JsonValue };
  /** Who is notified when the timeout is near. */
  escalate?: string[];
  /** Webhook that receives the signed reply (see `verifyWebhook`). */
  callbackUrl?: string;
  card?: Card;
}

/** Options of a single API call. */
export interface RequestOptions {
  /** Cancels the call (and any wait). */
  signal?: AbortSignal;
  /** Overrides the client's per-request timeout (ms). */
  timeoutMs?: number;
}

export interface AskOptions extends RequestOptions {
  /**
   * Idempotency key for `POST /v0/asks`. Generated when omitted, so a retry
   * never creates the question set twice.
   */
  idempotencyKey?: string;
  /**
   * Maximum time (ms) to wait for the reply on the client. When it elapses
   * while the question set is still open, `AskPendingError` is thrown.
   * Default: no limit (the question set's own `timeout` ends the wait).
   */
  maxWaitMs?: number;
}

// ---------------------------------------------------------------------------
// Person tokens (your own app shows a person's inbox)
// ---------------------------------------------------------------------------

/** Lifetime of a person token: `"30m"`, `"1h"`, `"12h"`… or a number of seconds. */
export type MemberTokenTtl = `${number}${"s" | "m" | "h"}` | number;

/** Input of `notific.members.issueToken()`. */
export interface IssueMemberTokenInput {
  /** E-mail of the person. They become a member of your workspace when they are not one yet. */
  email: string;
  /** The person's id in your own system. */
  externalId?: string;
  /** Name used when the account or the membership is created now. */
  displayName?: string;
  /** Default 1 hour, max 12 hours. */
  ttl?: MemberTokenTtl;
}

/** A notific.me account. */
export interface MemberUser {
  id: string;
  email: string;
  /** `@handle` without the `@`. */
  handle: string;
  displayName: string;
  /** `en`, `pt-BR` or `es`. */
  locale: string;
  /** API path of the profile photo, when there is one. */
  avatarUrl?: string;
  createdAt: string;
}

/** Result of `notific.members.issueToken()`. Hand `token` to your own app, never to anyone else. */
export interface MemberToken {
  /** Person token (`nm_dlg_…`), sent as `Authorization: Bearer <token>`. */
  token: string;
  tokenType: "Bearer";
  /** RFC 3339. Issue a new token before it expires. */
  expiresAt: string;
  /** The only workspace this token can see (the one of your service token). */
  workspaceId: string;
  user: MemberUser;
  /** `true` when the person became a member of your workspace now. */
  membershipCreated: boolean;
}

/** Input of `notific.members.revokeTokens()`. */
export interface RevokeMemberTokensInput {
  /** E-mail of the person whose tokens are revoked. */
  email: string;
}

/** Result of `notific.members.revokeTokens()`. */
export interface RevokeMemberTokensResult {
  /** How many active person tokens were revoked. */
  revoked: number;
}

export type AskStatus = "open" | "answered" | "timeout" | "expired" | "cancelled";

/** A question set just created (or read) on the server. */
export interface AskInfo {
  id: string;
  status: AskStatus;
  version: number;
  level: Level;
  title: string;
  createdAt: string;
  timeoutAt?: string;
  recipients?: string[];
  notificationId?: string;
  contentHash?: string;
  pollUrl?: string;
}
