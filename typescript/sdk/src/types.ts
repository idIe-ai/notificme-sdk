/**
 * Public, camelCase types of the SDK. The SDK converts them to the
 * snake_case wire format of the notific.me protocol (protocol/schemas).
 */

import type { UntrustedText } from "./untrusted";

/** JSON value. */
export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

export type Severity = "info" | "low" | "medium" | "high" | "critical";
export type Retention = "ephemeral" | "standard" | "regulated";
/** Decision level: 0 = tap, 1 = unlock, 2+ = device signature. */
export type Level = 0 | 1 | 2 | 3 | 4;
/** Duration such as `"30s"`, `"30m"`, `"2h"`, `"3d"`; a number means seconds. */
export type Duration = `${number}${"s" | "m" | "h" | "d"}` | number;

// ---------------------------------------------------------------------------
// Card
// ---------------------------------------------------------------------------

export interface TextBlock {
  type: "text";
  /** Markdown-lite text. */
  text: string;
}
export interface MetricBlock {
  type: "metric";
  label: string;
  value: number | string;
  unit?: string;
  /** e.g. `"+18%"` */
  delta?: string;
  /** Which way is good: `"higher"` (default) or `"lower"` (a default rate, a response time). */
  better?: "higher" | "lower";
}
export interface ChartBlock {
  type: "chart";
  kind: "line" | "bar";
  x?: string[];
  series: { name: string; values: number[] }[];
}
export interface TableBlock {
  type: "table";
  columns: string[];
  rows: (string | number | null)[][];
}
export interface ListBlock {
  type: "list";
  items: { text: string; icon?: string }[];
}
export interface ImageBlock {
  type: "image";
  src: string;
  alt?: string;
}
export interface ProgressBlock {
  type: "progress";
  /** 0..1 */
  value?: number;
  steps?: string[];
  current?: number;
}
export interface ButtonsBlock {
  type: "buttons";
  buttons: { label: string; url?: string; action?: string }[];
}
/** Renders a question of the question set (yesno, single or multi). */
export interface OptionsBlock {
  type: "options";
  questionId: string;
}
/** Renders a question of the question set (text, voice, number or date). */
export interface InputBlock {
  type: "input";
  questionId: string;
}
export type CardBlock =
  | TextBlock
  | MetricBlock
  | ChartBlock
  | TableBlock
  | ListBlock
  | ImageBlock
  | ProgressBlock
  | ButtonsBlock
  | OptionsBlock
  | InputBlock;

export interface Card {
  title?: string;
  theme?: { accent?: string; icon?: string };
  /** 1 to 40 blocks. */
  blocks: CardBlock[];
}

// ---------------------------------------------------------------------------
// Events
// ---------------------------------------------------------------------------

export interface EventContent {
  /** Short text for push, watch and simple channels (max 240 characters). */
  summary: string;
  card?: Card;
  rich?: { htmlRef: string; height?: number };
}

/** Event for `notific.send()`. */
export interface EventInput {
  /**
   * Your own id for the event, used for idempotency. When omitted the SDK
   * generates one, so automatic retries never create duplicates.
   */
  id?: string;
  /** Sender name. Defaults to the client's `source` option. */
  source?: string;
  /** Dotted lowercase type, e.g. `"container.die"`. */
  type: string;
  /** Defaults to `"info"`. */
  severity?: Severity;
  /** Defaults to now. */
  occurredAt?: Date | string;
  /**
   * Recipients: `@handle`, member e-mail or group (`#all`, `#admins`, `#owners`,
   * `#finance`, `#finance>=manager`). When omitted, the workspace owners.
   */
  to?: string | string[];
  /** Free-form data; sent as is (keys are not converted). */
  payload?: Record<string, unknown>;
  /** Events with the same key within the dedup window are merged. */
  dedupKey?: string;
  /** How long the notification stays relevant, e.g. `"30m"`. */
  ttl?: Duration;
  /** Event type that closes this notification, e.g. `"container.healthy"`. */
  expiresWhen?: string;
  /** Live card id: events with the same `cardId` update the same card. */
  cardId?: string;
  /** When `true` and `cardId` is omitted, the SDK generates a `cardId` (returned in the result). */
  live?: boolean;
  retention?: Retention;
  /** Shortcut for `content.summary`. */
  summary?: string;
  /** Shortcut for `content.card`. */
  card?: Card;
  content?: EventContent;
}

/** Result of `send()` / `update()` (`202 Accepted`). */
export interface SendResult {
  /** Server-side event id. */
  id: string;
  /** `duplicate` when merged by `dedupKey`. */
  status: "queued" | "duplicate";
  duplicateOf?: string;
  /** The event `id` you sent (or the one generated by the SDK). */
  senderId?: string;
  receivedAt: string;
  /** Live card id, when the event has one. Pass it to `update()`. */
  cardId?: string;
  /** `true` when the server returned a stored response for a repeated id. */
  replayed: boolean;
}

// ---------------------------------------------------------------------------
// Questions
// ---------------------------------------------------------------------------

interface QuestionBase<Id extends string> {
  /** Unique id inside the question set; answers are keyed by it. */
  id: Id;
  /** The question shown to the human. */
  text: string;
  /** When `true` the human may skip it (the answer may be `undefined`). */
  optional?: boolean;
  /** Minimum decision level for this question. */
  level?: Level;
}

export interface YesNoQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "yesno";
}
export interface SingleQuestion<Id extends string = string, O extends string = string> extends QuestionBase<Id> {
  type: "single";
  options: readonly O[];
  /** Lets the human type another answer (returned as `UntrustedText`). */
  allowOther?: boolean;
}
export interface MultiQuestion<Id extends string = string, O extends string = string> extends QuestionBase<Id> {
  type: "multi";
  options: readonly O[];
  /** Lets the human add free text (see `details[id].freeText`). */
  allowOther?: boolean;
}
export interface TextQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "text";
}
export interface VoiceQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "voice";
}
export interface NumberQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "number";
}
export interface DateQuestion<Id extends string = string> extends QuestionBase<Id> {
  type: "date";
}

export type Question =
  | YesNoQuestion
  | SingleQuestion
  | MultiQuestion
  | TextQuestion
  | VoiceQuestion
  | NumberQuestion
  | DateQuestion;

export type QuestionType = Question["type"];

/** Answer of a `voice` question. */
export interface VoiceAnswer {
  /** Transcription (untrusted). */
  text?: UntrustedText;
  /** Reference of the recorded audio. */
  audioRef?: string;
}

/** Answer value type of a question. */
export type AnswerValue<Q> = Q extends { type: "yesno" }
  ? boolean
  : Q extends { type: "single"; options: readonly (infer O)[] }
    ? Q extends { allowOther: true }
      ? O | UntrustedText
      : O
    : Q extends { type: "multi"; options: readonly (infer O)[] }
      ? O[]
      : Q extends { type: "text" }
        ? UntrustedText
        : Q extends { type: "voice" }
          ? VoiceAnswer
          : Q extends { type: "number" }
            ? number
            : Q extends { type: "date" }
              ? string
              : unknown;

type IsOptional<Q> = Q extends { optional: true } ? true : false;

/** Answers keyed by question id (all present when `status` is `answered`, except optional ones). */
export type Answers<Qs extends readonly Question[]> = {
  [Q in Qs[number] as Q["id"]]: IsOptional<Q> extends true ? AnswerValue<Q> | undefined : AnswerValue<Q>;
};

/** Answers when the question set timed out or was rejected: any of them may be missing. */
export type PartialAnswers<Qs extends readonly Question[]> = {
  [Q in Qs[number] as Q["id"]]: AnswerValue<Q> | undefined;
};

/** Everything the server returned for one answer. */
export interface AnswerDetail {
  questionId: string;
  questionText: string;
  /** Raw value (`true`, `"Approve"`, `["a","b"]`, `42`, `"2026-11-04"`…). */
  value?: JsonValue;
  /** Free text typed by the human. Untrusted. */
  freeText?: UntrustedText;
  audioRef?: string;
}

/**
 * How the person confirmed the answer. `delegated`: inside your own app with a
 * person token (`notific.members.issueToken()`), levels 0 and 1 only.
 */
export type AuthMethod = "tap" | "unlock" | "biometric" | "device_pin" | "app_password" | "totp" | "delegated";

export interface AnsweredBy {
  /** E-mail or handle of who answered. */
  identity: string;
  deviceId: string;
  levelUsed: Level;
  authMethod?: AuthMethod;
  /** Group through which the person decided (`"#finance"`), when the question has a decision rule. */
  group?: string;
  /** The person's authority level in that group (`"manager"`). */
  authorityLevel?: string;
}

/**
 * Decision rule (who may decide and what closes the question):
 * - `any`: the first answer closes it (the default);
 * - `quorum`: `required` approvals;
 * - `majority`: more than half of the eligible people;
 * - `unanimous`: every eligible person;
 * - `each_group`: one approval from each entry of `by` ("four eyes").
 *
 * Rejections count but do not veto: the question closes as rejected once approval
 * can no longer be reached (unless `veto: true`). One person, one vote.
 */
export type DecisionRule = "any" | "quorum" | "majority" | "unanimous" | "each_group";

/** `decision` block of `ask()`. Rules other than `any` need the Team plan or above. */
export interface DecisionInput {
  /**
   * Who may decide: `#group`, `#group>=authority_level` (e.g. `"#finance>=manager"`),
   * `@handle` or a member's e-mail. They also receive the card. Default: everyone in `to`.
   */
  by?: string | string[];
  rule?: DecisionRule;
  /** Approvals needed with `rule: "quorum"`. */
  required?: number;
  /** A single rejection closes the question as rejected. */
  veto?: boolean;
  /** Question whose answer is the vote (`yesno`, or `single` with `approveOptions`). Default: the first question. */
  question?: string;
  /** With a single-choice vote question: the options that count as approval. */
  approveOptions?: string[];
  /** The member who made the request (`@handle` or e-mail): they never approve their own request. */
  requestedBy?: string;
}

/** A step of the escalation chain. */
export interface EscalationStep {
  /** Time since the question was sent, e.g. `"30m"`. Default: half of the timeout. */
  after?: Duration;
  /** Who also receives it and may decide from then on (`#group`, `#group>=level`, `@handle`, e-mail). */
  to: string | string[];
}

/** How the decision rule closed the question (in the signed reply). */
export interface DecisionOutcome {
  rule: DecisionRule;
  required?: number;
  eligible: number;
  approvals: number;
  rejections: number;
  /** `approved` or `rejected` (approval impossible, or a veto). */
  outcome?: "approved" | "rejected";
  by?: string[];
  escalationStep?: number;
}

/** One vote (one person, one vote). */
export interface Vote {
  identity: string;
  handle?: string;
  approve: boolean;
  answeredAt: string;
  levelUsed?: Level;
  authMethod?: AuthMethod;
  group?: string;
  authorityLevel?: string;
}

/** Partial state of the decision rule while the question is open (`getAsk()`). */
export interface DecisionProgress {
  rule: DecisionRule;
  required: number;
  eligible: number;
  approvals: number;
  rejections: number;
  pending: number;
  outcome?: "approved" | "rejected";
  by?: string[];
  votes: { handle?: string; displayName: string; approve: boolean; at: string; group?: string; authorityLevel?: string }[];
  escalationStep: number;
  escalationSteps: number;
  nextEscalationAt?: string;
}

export interface ReplySignature {
  alg: "ES256" | "Ed25519";
  keyId?: string;
  value: string;
}

/**
 * Electronic signature the person applied to the answer (asked with
 * `requireSignature`). Images are PNG in base64; hashes are `sha256:<hex>` of
 * the PNG bytes. The reply signature covers it like every other field.
 */
export interface ESignature {
  /** Full name the person adopted. */
  name: string;
  initials: string;
  /** `typed`: the name in a cursive style; `drawn`: drawn by finger or mouse. */
  method: "typed" | "drawn";
  /** Cursive style of a typed signature (`great-vibes`, `dancing-script`, `sacramento`, `mr-dafoe`). */
  style?: string;
  signaturePng: string;
  signatureSha256: string;
  initialsPng: string;
  initialsSha256: string;
  consentVersion?: string;
  /** When the person adopted this signature. */
  adoptedAt: string;
}

/**
 * How the face of the person who answered was checked (asked with
 * `requireFace`). No biometric data and no score.
 */
export interface FaceVerification {
  /**
   * `verified`: the face matched the one the person enrolled in the
   * organization. `fallback`: the face was NOT verified and the organization
   * accepts the authenticator code instead (see `reason`).
   */
  result: "verified" | "fallback";
  /** Only on `fallback`: the person ran out of attempts, or never enrolled their face. */
  reason?: "attempts_exhausted" | "not_enrolled";
  verificationId?: string;
  /** Version of the face model that compared the faces. */
  model?: string;
  verifiedAt: string;
}

interface AskResultBase {
  /** Question set id. */
  id: string;
  version: number;
  /**
   * Natural-language summary of the decision, ready for an AI agent. Free
   * text inside it is quoted and labelled as untrusted by the server. Written
   * in the ask's `locale` (default `"en"`).
   */
  asText: string;
  answeredBy?: AnsweredBy;
  answeredAt?: string;
  contentHash?: string;
  /** The person's electronic signature, when the question set had `requireSignature`. */
  eSignature?: ESignature;
  /** How the person's face was checked, when the question set had `requireFace`. */
  faceVerification?: FaceVerification;
  signature?: ReplySignature;
  /** How the decision rule closed it (questions with `decision`). */
  decision?: DecisionOutcome;
  /** Every vote, in order (questions with a decision rule). */
  votes?: Vote[];
  /** Every answer with its question text, raw value and free text. */
  details: Record<string, AnswerDetail>;
  /** The reply exactly as received (snake_case wire format). */
  raw: Record<string, unknown>;
}

export interface AnsweredAskResult<Qs extends readonly Question[]> extends AskResultBase {
  status: "answered";
  timedOut: false;
  answers: Answers<Qs>;
}

export interface UnansweredAskResult<Qs extends readonly Question[]> extends AskResultBase {
  /**
   * `timeout`: nobody answered in time (`onTimeout` values are applied). `rejected`:
   * the decision rule closed it as rejected (approval impossible, or a veto).
   */
  status: "timeout" | "rejected";
  timedOut: boolean;
  answers: PartialAnswers<Qs>;
}

/** Final result of `ask()`. Narrow on `status` to get required answers. */
export type AskResult<Qs extends readonly Question[] = readonly Question[]> =
  | AnsweredAskResult<Qs>
  | UnansweredAskResult<Qs>;

/** Question set for `ask()` / `createAsk()`. */
export interface AskInput<Qs extends readonly Question[] = readonly Question[]> {
  /** Recipients (handle, member or group). When omitted, subscriptions decide. */
  to?: string | string[];
  /** Up to 160 characters. */
  title: string;
  /** Why you are asking (up to 4000 characters). */
  context?: string;
  /** 1 to 20 questions. */
  questions: Qs;
  /** Minimum decision level (default 1). The workspace may require more. */
  level?: Level;
  /**
   * How urgent it is (default `"high"`). `"critical"`: the person's app may take
   * the full screen with an alarm until they decide (their choice in the app).
   */
  severity?: Severity;
  /**
   * Your language, the one `asText` comes back in: `"en"` (default), `"pt-BR"`
   * or `"es"` (`"pt"`, `"es-MX"`… map to them). It does not change what the
   * human sees.
   */
  locale?: string;
  /** Shorthand for `decision: { rule: "quorum", required }` among `to`. */
  quorum?: number;
  /** Who may decide and which rule closes the question. */
  decision?: DecisionInput;
  /** Whether the app may answer while offline. */
  offline?: "allowed" | "denied";
  /** How long the humans have, e.g. `"30m"`. */
  timeout?: Duration;
  /** Answers applied when nobody answers in time, by question id. */
  onTimeout?: { [K in Qs[number]["id"]]?: JsonValue };
  /**
   * Escalation chain: if still open after each step's time, the step's recipients
   * also receive it and may decide. A plain string is `{ to: string }` at half the timeout.
   */
  escalate?: (EscalationStep | string)[];
  /** Webhook that receives the signed reply (see `verifyWebhook`). */
  callbackUrl?: string;
  /**
   * Ask the person to sign the answer with their electronic signature (typed
   * in a cursive style or drawn) and initials, on top of `level`. The result
   * carries it in `eSignature`. Pro plans and above (`plan_required` otherwise).
   */
  requireSignature?: boolean;
  /**
   * Only accept the answer after the person's face is verified, in the
   * notific.me app, against the face they enrolled in the organization. The
   * result reports it in `faceVerification`. Business plans and above with
   * face verification turned on (`plan_required` / `face_disabled` otherwise).
   */
  requireFace?: boolean;
  card?: Card;
}

/** Options of a single API call. */
export interface RequestOptions {
  /** Cancels the call (and any wait). */
  signal?: AbortSignal;
  /** Overrides the client's per-request timeout (ms). */
  timeoutMs?: number;
}

export interface AskOptions extends RequestOptions {
  /**
   * Idempotency key for `POST /v0/asks`. Generated when omitted, so a retry
   * never creates the question set twice.
   */
  idempotencyKey?: string;
  /**
   * Maximum time (ms) to wait for the reply on the client. When it elapses
   * while the question set is still open, `AskPendingError` is thrown.
   * Default: no limit (the question set's own `timeout` ends the wait).
   */
  maxWaitMs?: number;
}

