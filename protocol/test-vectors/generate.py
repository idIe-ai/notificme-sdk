"""Regenerates webhook-signature.json, the shared test vector every SDK verifies.

The key is derived from a fixed seed, so the output is deterministic:

    pip install cryptography
    python protocol/test-vectors/generate.py
"""

from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

SEED = bytes(range(1, 33))
TIMESTAMP = 1793800000

REPLY = {
    "question_set_id": "019a2b3c-4d5e-7f60-8a9b-0c1d2e3f4a5b",
    "version": 1,
    "status": "answered",
    "answers": [
        {"question_id": "action", "question_text": "What should we do?", "value": "Approve"},
        # Non-ASCII on purpose: SDKs must sign/verify the exact UTF-8 bytes.
        {"question_id": "note", "question_text": "Notes", "free_text": "Only after 10 pm ✓"},
    ],
    "as_text": "Jimmy answered: What should we do? Approve.",
    "answered_by": {
        "identity": "jimmy@example.com",
        "device_id": "019a2b3c-0000-7000-8000-000000000001",
        "level_used": 2,
        "auth_method": "biometric",
    },
    "signature": {"alg": "Ed25519", "key_id": "dev", "value": "c2ln"},
}


def b64url(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).decode().rstrip("=")


def main() -> None:
    key = Ed25519PrivateKey.from_private_bytes(SEED)
    pub = key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    # Key id: first 8 bytes of SHA-256 of the public key, base64url (same as the server).
    kid = b64url(hashlib.sha256(pub).digest()[:8])
    body = json.dumps(REPLY, ensure_ascii=False, separators=(",", ":"))
    sig = key.sign(f"{TIMESTAMP}.".encode() + body.encode("utf-8"))
    vector = {
        "comment": "Generated by protocol/test-vectors/generate.py. Do not edit by hand.",
        "seed": b64url(SEED),
        "key_id": kid,
        "public_key": b64url(pub),
        "jwks": {
            "keys": [{"alg": "EdDSA", "crv": "Ed25519", "kid": kid, "kty": "OKP", "use": "sig", "x": b64url(pub)}]
        },
        "timestamp": TIMESTAMP,
        "body": body,
        "header": f"t={TIMESTAMP},kid={kid},sig={b64url(sig)}",
    }
    out = Path(__file__).with_name("webhook-signature.json")
    out.write_text(json.dumps(vector, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
