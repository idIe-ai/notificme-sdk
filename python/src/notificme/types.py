"""Public types of the SDK.

Inputs (cards, questions) are plain dicts in the protocol's snake_case, as in
``protocol/schemas``; the TypedDicts below only help type checkers. Results are
dataclasses.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Union

if sys.version_info >= (3, 11):
    from typing import Literal, NotRequired, TypedDict
else:  # pragma: no cover
    from typing_extensions import Literal, NotRequired, TypedDict

from .untrusted import UntrustedText

Severity = Literal["info", "low", "medium", "high", "critical"]
Retention = Literal["ephemeral", "standard", "regulated"]
QuestionType = Literal["yesno", "single", "multi", "text", "voice", "number", "date"]
AskStatus = Literal["open", "answered", "timeout", "expired", "cancelled"]


class Question(TypedDict):
    """A question of ``ask()``, as in ``question-set.schema.json``."""

    #: Unique id inside the question set; answers are keyed by it.
    id: str
    type: QuestionType
    #: The question shown to the human.
    text: str
    #: Options of ``single`` and ``multi`` questions.
    options: NotRequired[List[str]]
    #: Lets the human type another answer (``single``/``multi``).
    allow_other: NotRequired[bool]
    #: When ``True`` the human may skip it.
    optional: NotRequired[bool]
    #: Minimum decision level for this question (0 = tap, 1 = unlock, 2+ = device signature).
    level: NotRequired[int]


class Card(TypedDict):
    """A declarative card, as in ``card.schema.json``."""

    title: NotRequired[str]
    theme: NotRequired[Dict[str, str]]
    #: 1 to 40 blocks, e.g. ``{"type": "metric", "label": "Errors", "value": 3}``.
    blocks: List[Dict[str, Any]]


@dataclass(frozen=True)
class SendResult:
    """Result of ``send()`` / ``update()`` (``202 Accepted``)."""

    #: Server-side event id.
    id: str
    #: ``duplicate`` when merged by ``dedup_key``.
    status: str
    received_at: str
    #: ``True`` when the server returned a stored response for a repeated id.
    replayed: bool = False
    duplicate_of: Optional[str] = None
    #: The event ``id`` you sent (or the one generated by the SDK).
    sender_id: Optional[str] = None
    #: Live card id, when the event has one. Pass it to ``update()``.
    card_id: Optional[str] = None


@dataclass
class AskInfo:
    """A question set just created (or read) on the server."""

    id: str
    status: str
    version: int
    level: int
    title: str
    created_at: str
    timeout_at: Optional[str] = None
    recipients: Optional[List[str]] = None
    notification_id: Optional[str] = None
    content_hash: Optional[str] = None
    poll_url: Optional[str] = None
    #: The raw reply (snake_case), present when ``answered`` or ``timeout``.
    reply: Optional[Dict[str, Any]] = None


@dataclass
class AskHandle(AskInfo):
    """Handle of a question set created with ``create_ask()``. Call ``wait()`` for the reply."""

    _wait: Optional[Callable[..., Any]] = field(default=None, repr=False, compare=False)

    def wait(self, *, max_wait: Optional[float] = None) -> Any:
        """Waits (long-poll) for the reply. Returns an ``AskResult`` (awaitable on the async client)."""
        if self._wait is None:  # pragma: no cover
            raise RuntimeError("This handle is not bound to a client")
        return self._wait(max_wait=max_wait)


@dataclass(frozen=True)
class VoiceAnswer:
    """Answer of a ``voice`` question."""

    #: Transcription (untrusted).
    text: Optional[UntrustedText] = None
    #: Reference of the recorded audio.
    audio_ref: Optional[str] = None


@dataclass(frozen=True)
class AnswerDetail:
    """Everything the server returned for one answer."""

    question_id: str
    question_text: str
    #: Raw value (``True``, ``"Approve"``, ``["a", "b"]``, ``42``, ``"2026-11-04"``…).
    value: Any = None
    #: Free text typed by the human. Untrusted.
    free_text: Optional[UntrustedText] = None
    audio_ref: Optional[str] = None


@dataclass(frozen=True)
class AnsweredBy:
    #: E-mail or handle of who answered.
    identity: str
    device_id: str
    level_used: int
    auth_method: Optional[str] = None


@dataclass(frozen=True)
class ReplySignature:
    alg: str
    value: str
    key_id: Optional[str] = None


@dataclass
class AskResult:
    """Final result of ``ask()``.

    ``answers`` maps question id → value, converted per question type:
    ``yesno`` → ``bool``, ``single`` → ``str`` (``UntrustedText`` when typed as
    "other"), ``multi`` → ``list[str]``, ``text`` → ``UntrustedText``,
    ``voice`` → ``VoiceAnswer``, ``number`` → number, ``date`` → ``str``.
    """

    #: Question set id.
    id: str
    version: int
    #: ``answered``, ``timeout`` (``on_timeout`` values applied) or ``rejected``.
    status: str
    timed_out: bool
    #: Natural-language summary of the decision, ready for an AI agent.
    as_text: str
    answers: Dict[str, Any]
    #: Every answer with its question text, raw value and free text.
    details: Dict[str, AnswerDetail]
    #: The reply exactly as received (snake_case wire format).
    raw: Dict[str, Any]
    answered_by: Optional[AnsweredBy] = None
    answered_at: Optional[str] = None
    content_hash: Optional[str] = None
    signature: Optional[ReplySignature] = None


@dataclass(frozen=True)
class VerifiedSignature:
    #: Signature timestamp (unix seconds).
    timestamp: int
    #: Id of the key that signed it, when the header carries one.
    key_id: Optional[str] = None


@dataclass
class Webhook:
    """A verified webhook."""

    timestamp: int
    key_id: Optional[str]
    #: ``Notificme-Webhook-Id``: identical on every retry; use it to deduplicate.
    id: Optional[str]
    #: ``Notificme-Topic``, e.g. ``reply``.
    topic: Optional[str]
    #: ``Notificme-Attempt`` (1, 2, …).
    attempt: Optional[int]
    #: The raw body as text.
    raw_body: str
    #: The parsed JSON body (snake_case, as sent).
    payload: Any
    #: For the ``reply`` topic: the reply as an ``AskResult``.
    reply: Optional[AskResult] = None


JsonValue = Union[str, int, float, bool, None, List[Any], Dict[str, Any]]
